const std = @import("std");
const Config = @This();
header: []const u8,
target: std.Target,
backtrace: bool,
bcheck: bool,

pub fn init(b: *std.Build, host: std.Build.ResolvedTarget) Config {
    const triple = b.option([]const u8, "tcc-target", "TinyCC code-generation target (defaults to -Dtarget)");
    const target = if (triple) |t| b.resolveTargetQuery(std.Target.Query.parse(.{ .arch_os_abi = t }) catch @panic("Invalid -Dtcc-target triple")).result else host.result;
    const arch = switch (target.cpu.arch) {
        .x86 => "I386",
        .x86_64 => "X86_64",
        .arm, .thumb => "ARM",
        .aarch64 => "ARM64",
        .riscv64 => "RISCV64",
        else => @panic("TinyCC supports x86, x86_64, arm, aarch64 and riscv64"),
    };
    const os = target.os.tag;
    switch (os) {
        .linux, .macos, .windows, .freebsd, .netbsd, .openbsd => {},
        else => @panic("Unsupported TinyCC operating system"),
    }
    if (os == .macos and target.cpu.arch != .aarch64 and target.cpu.arch != .x86_64) @panic("Mach-O requires aarch64 or x86_64");
    const bt = b.option(bool, "backtrace", "Enable stack backtraces") orelse true;
    const bc = b.option(bool, "bcheck", "Enable bounds checking (requires backtraces)") orelse bt;
    if (bc and !bt) @panic("Bounds checking requires -Dbacktrace=true");
    var root = b.option([]const u8, "sysroot", "TinyCC target system headers and libraries (macOS SDK auto-detected)") orelse "";
    if (os == .macos and root.len == 0 and b.graph.host.result.os.tag == .macos) {
        const result = std.process.run(b.allocator, b.graph.io, .{ .argv = &.{ "xcrun", "--show-sdk-path" } }) catch @panic("Set -Dsysroot to the macOS SDK path");
        if (result.term != .exited or result.term.exited != 0) @panic("Cannot find macOS SDK; set -Dsysroot");
        root = b.dupe(std.mem.trim(u8, result.stdout, "\r\n "));
    }
    const sep = if (host.result.os.tag == .windows) ";" else ":";
    const triplet = b.option([]const u8, "triplet", "Linux multiarch directory name") orelse switch (target.cpu.arch) {
        .x86 => "i386-linux-gnu",
        .x86_64 => "x86_64-linux-gnu",
        .aarch64 => "aarch64-linux-gnu",
        .arm, .thumb => "arm-linux-gnueabihf",
        .riscv64 => "riscv64-linux-gnu",
        else => unreachable,
    };
    const inc = b.option([]const u8, "sysinclude", "TinyCC system include search paths") orelse if (os == .windows) b.fmt("{{B}}/include{s}{{B}}/include/winapi", .{sep}) else if (os == .macos) b.fmt("{{B}}/include{s}{s}/usr/include", .{ sep, root }) else b.fmt("{{B}}/include{s}{s}/usr/local/include{s}{s}/usr/include/{s}{s}{s}/usr/include", .{ sep, root, sep, root, triplet, sep, root });
    const libs = b.option([]const u8, "libpaths", "TinyCC library search paths") orelse if (os == .windows) "{B}/lib" else if (os == .macos) b.fmt("{{B}}{s}/usr/lib", .{sep}) else b.fmt("{{B}}{s}{s}/usr/lib/{s}{s}{s}/lib/{s}{s}{s}/usr/lib64{s}{s}/lib64{s}{s}/usr/lib{s}{s}/lib{s}{s}/usr/local/lib", .{ sep, root, triplet, sep, root, triplet, sep, root, sep, root, sep, root, sep, root, sep, root });
    const crt = b.option([]const u8, "crtprefix", "TinyCC CRT object search paths") orelse libs;
    var h: std.Io.Writer.Allocating = .init(b.allocator);
    const w = &h.writer;
    w.print("/* Generated by Zig. */\n#define TCC_VERSION {s}\n#define CC_NAME CC_clang\n#define GCC_MAJOR 21\n#define GCC_MINOR 1\n#define TCC_TARGET_{s} 1\n#define CONFIG_TCC_PREDEFS 1\n#define CONFIG_TCC_BACKTRACE {d}\n#define CONFIG_TCC_BCHECK {d}\n", .{ cString(b, std.mem.trim(u8, @embedFile("../VERSION"), "\r\n ")), arch, @intFromBool(bt), @intFromBool(bc) }) catch @panic("OOM");
    const os_define: ?[]const u8 = switch (os) {
        .macos => "TCC_TARGET_MACHO",
        .windows => "TCC_TARGET_PE",
        .freebsd => "TARGETOS_FreeBSD",
        .netbsd => "TARGETOS_NetBSD",
        .openbsd => "TARGETOS_OpenBSD",
        else => null,
    };
    if (os_define) |name| w.print("#define {s} 1\n", .{name}) catch @panic("OOM");
    if (target.cpu.arch == .arm or target.cpu.arch == .thumb) {
        w.writeAll("#define TCC_ARM_EABI 1\n#define TCC_ARM_VFP 1\n") catch @panic("OOM");
        if (target.abi == .gnueabihf or target.abi == .musleabihf) w.writeAll("#define TCC_ARM_HARDFLOAT 1\n") catch @panic("OOM");
    }
    const dwarf = b.option(u8, "dwarf", "Default DWARF version (0 means stabs)") orelse @as(u8, if (os == .macos) 4 else 0);
    w.print("#define CONFIG_DWARF_VERSION {d}\n", .{dwarf}) catch @panic("OOM");
    if (os == .macos) w.writeAll("#define CONFIG_CODESIGN 1\n") catch @panic("OOM");
    if (target.abi.isMusl()) w.writeAll("#define CONFIG_TCC_MUSL 1\n") catch @panic("OOM");
    const interp = b.option([]const u8, "elfinterp", "ELF dynamic loader path") orelse switch (os) {
        .freebsd => "/libexec/ld-elf.so.1",
        .netbsd => "/usr/libexec/ld.elf_so",
        .openbsd => "/usr/libexec/ld.so",
        else => if (target.abi.isMusl()) b.fmt("/lib/ld-musl-{s}.so.1", .{if (target.cpu.arch == .x86) "i386" else @tagName(target.cpu.arch)}) else "",
    };
    const tccdir = b.option([]const u8, "tccdir", "Compiled-in TinyCC support directory") orelse b.getInstallPath(.lib, "tcc");
    for ([_][2][]const u8{ .{ "CONFIG_TCCDIR", tccdir }, .{ "CONFIG_TCC_SYSINCLUDEPATHS", inc }, .{ "CONFIG_TCC_LIBPATHS", libs }, .{ "CONFIG_TCC_CRTPREFIX", crt } }) |item| w.print("#define {s} {s}\n", .{ item[0], if (std.mem.eql(u8, item[0], "CONFIG_TCCDIR")) cString(b, item[1]) else cPaths(b, item[1], sep[0]) }) catch @panic("OOM");
    if (interp.len != 0) w.print("#define CONFIG_TCC_ELFINTERP {s}\n", .{cString(b, interp)}) catch @panic("OOM");
    return .{ .header = h.toOwnedSlice() catch @panic("OOM"), .target = target, .backtrace = bt, .bcheck = bc };
}

fn cString(b: *std.Build, value: []const u8) []const u8 {
    var w: std.Io.Writer.Allocating = .init(b.allocator);
    w.writer.writeByte('"') catch @panic("OOM");
    for (value) |c| {
        if (c == '\\' or c == '"') w.writer.writeByte('\\') catch @panic("OOM");
        w.writer.writeByte(c) catch @panic("OOM");
    }
    w.writer.writeByte('"') catch @panic("OOM");
    return w.toOwnedSlice() catch @panic("OOM");
}

// PATHSEP is evaluated by the actual compiler host, including the bootstrap.
fn cPaths(b: *std.Build, value: []const u8, separator: u8) []const u8 {
    var parts = std.mem.splitScalar(u8, value, separator);
    var strings: std.array_list.Managed([]const u8) = .init(b.allocator);
    while (parts.next()) |part| strings.append(cString(b, part)) catch @panic("OOM");
    return std.mem.join(b.allocator, " PATHSEP ", strings.items) catch @panic("OOM");
}
